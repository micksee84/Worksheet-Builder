"""Trace the feelings faces (emoji + children) into src/blocks/feelingFaces.ts"""
import sys, json
sys.path.insert(0, '/home/claude/krea')
from trace_art import trace
U = '/mnt/user-data/uploads/Feelings/'
EMOJI = ['angry','bored','calm','confused','excited','grumpy','happy','loving','proud','sad','scared','shy','silly','surprised','tired','worried','yucky']
KIDF = ['angry','bored','calm','confused','excited','grumpy','happy','loving','proud']
KIDS = ['girl-puffs','boy-afro','girl-bob','boy-sidepart','girl-hijab','boy-curly']
out = {}
for f in EMOJI:
    out['feeling-' + f] = trace(U + 'Emoji faces/17-feelings_%s.png' % f, (50, 50, 94, 'centre'))
for f in KIDF:
    for c in KIDS:
        out['kid-%s-%s' % (c, f)] = trace(U + 'Kids faces/17-kids_%s-%s.png' % (f, c), (50, 50, 94, 'centre'))
lines = ['/**', ' * @license', ' * Sunshine Brigade Worksheet Builder - Feelings faces (version 0.5)', ' *',
 ' * 17 round emoji faces (feeling-<feeling>) and 54 children\'s faces (kid-<child>-<feeling>)',
 ' * from the Krea reference set. Each sits in a 100 x 100 box, centred on 50,50, line weight HAND_LINE.',
 ' *', ' * Generated by build_faces.py: re-trace rather than editing these paths by hand.', ' */', '',
 "import type { PictureEntry } from './pictureArt';", '',
 'export const FACE_SHAPES: Record<string, PictureEntry> = {']
for k, (p, kk) in out.items():
    lines.append("  '%s': {\n    p: '%s',\n    k: '%s',\n  }," % (k, p, kk))
lines.append('};\n')
open('/home/claude/worksheet-builder/src/blocks/feelingFaces.ts', 'w').write('\n'.join(lines))
print(len(out))
